/**
 * drift.mjs — one-way generation with handoff.
 *
 * An emitted .js file carries a hash of the IR it was generated from, as a
 * leading comment. Once a human edits that file, re-running the generator
 * for the same lesson id must NOT silently overwrite their edits — the IR is
 * a birth certificate, not a live upstream. check() compares the file's
 * embedded hash against a hash of the file's OWN current content (excluding
 * the hash line itself) recomputed the same way generate() would: if they
 * still match, nothing has touched the file since it was generated, and
 * overwriting is safe. If they don't match, a human edited it — refuse
 * unless --force.
 */
import crypto from 'node:crypto';

const MARKER_RE = /^\/\* @generated by tools\/author — sha256:([0-9a-f]{16}) \*\/\n/;

function hash(text) {
  return crypto.createHash('sha256').update(text, 'utf8').digest('hex').slice(0, 16);
}

/** Wrap emitted source with a hash of ITSELF (the body, not the IR) — so
 *  drift detection needs nothing but the file on disk to check itself. */
export function withDriftMarker(sourceBody) {
  const sha = hash(sourceBody);
  return `/* @generated by tools/author — sha256:${sha} */\n${sourceBody}`;
}

/**
 * @returns {'missing'|'clean'|'edited'} — 'missing' = no marker (hand-written
 *   or never generated), 'clean' = safe to overwrite, 'edited' = a human
 *   changed it since generation, refuse without --force.
 */
export function checkDrift(fileText) {
  const m = MARKER_RE.exec(fileText);
  if (!m) return 'missing';
  const body = fileText.slice(m[0].length);
  return hash(body) === m[1] ? 'clean' : 'edited';
}
